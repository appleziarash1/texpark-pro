/* Builds js/bd-locations.js (and the reference data/bd-locations.json) from the
   pinned MIT-licensed package @olism/bd-geo.

   Run: node tools/gen-bd-locations.js [path-to-a-local-index.cjs]
   With no argument it downloads the pinned version from jsDelivr. The package is
   never installed into the app; only the extracted name lists are committed, so
   the shipped app has no runtime dependency.

   Why this dataset: it pairs each of the 64 districts with its 556 upazilas AND
   the city thanas that Steadfast actually routes on (Mirpur, Dhanmondi, Badda,
   ...). The government upazila lists leave those city thanas out, which is why a
   Dhaka address would otherwise resolve to a district with no usable area. */
const fs = require('fs');
const path = require('path');
const https = require('https');

const PINNED = 'https://cdn.jsdelivr.net/npm/@olism/bd-geo@1.0.0/dist/index.cjs';
const VERSION = 'olism-bd-geo@1.0.0';
const root = path.join(__dirname, '..');

/* English spellings seen in the wild that differ from the dataset's own name.
   The dataset is not wrong; shopkeepers simply type the older or phonetic form. */
const DISTRICT_VARIANTS = {
  Chattogram: ['chittagong', 'chattagram', 'chattagon'],
  Cumilla: ['comilla'],
  Jashore: ['jessore'],
  Barishal: ['barisal'],
  Bogura: ['bogra'],
  "Cox's Bazar": ['coxs bazar', 'cox bazar'],
  Jhalokati: ['jhalokathi'],
  Khagrachhari: ['khagrachari'],
  Moulvibazar: ['maulvibazar', 'moulvi bazar'],
  Netrokona: ['netrakona'],
  Chapainawabganj: ['chapai nawabganj'],
  Brahmanbaria: ['brahmanbariya'],
  Narayanganj: ['narayangonj'],
  Munshiganj: ['munshigonj'],
  Narsingdi: ['narshingdi', 'norshingdi'],
  Gopalganj: ['gopalgonj'],
  Kishoreganj: ['kishorganj']
};

/* Lower-case, punctuation-free key so "Cox's Bazar" and "coxs bazar" fold together. */
function key(s) {
  return String(s || '').toLowerCase()
    .replace(/['\u2019`.]/g, '')
    .replace(/-/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function fetch(url) {
  return new Promise((resolve, reject) => {
    https.get(url, res => {
      if (res.statusCode !== 200) return reject(new Error('HTTP ' + res.statusCode + ' for ' + url));
      let d = ''; res.on('data', c => (d += c)); res.on('end', () => resolve(d));
    }).on('error', reject);
  });
}

(async () => {
  let src;
  const local = process.argv[2];
  if (local) { src = local; }
  else {
    const tmp = path.join(require('os').tmpdir(), 'bd-geo-' + Date.now() + '.cjs');
    const body = await fetch(PINNED);
    fs.writeFileSync(tmp, body);
    src = tmp;
    console.log('downloaded ' + PINNED + ' (' + body.length + ' bytes)');
  }

  const geo = require(path.resolve(src));
  const districts = geo.getDistricts();
  const thanas = geo.getThanas();
  const divisions = geo.getDivisions ? geo.getDivisions() : [];
  const divName = {};
  divisions.forEach(d => { divName[d.id] = d.name; });

  const byDistrict = {};
  thanas.forEach(t => { (byDistrict[t.districtId] = byDistrict[t.districtId] || []).push(t); });

  const out = districts.map(d => {
    const aliases = new Set([key(d.name), key(d.nameBn)]);
    (DISTRICT_VARIANTS[d.name] || []).forEach(a => aliases.add(key(a)));
    const ths = (byDistrict[d.id] || []).map(t => ({
      name: t.name,
      nameBn: t.nameBn,
      type: t.type === 'thana' ? 'thana' : 'upazila',
      aliases: Array.from(new Set([key(t.name), key(t.nameBn)])).filter(Boolean).sort()
    })).sort((a, b) => a.name.localeCompare(b.name));
    return {
      code: String(d.id),
      name: d.name,
      nameBn: d.nameBn,
      division: divName[d.divisionId] || '',
      aliases: Array.from(aliases).filter(Boolean).sort(),
      thanas: ths
    };
  }).sort((a, b) => a.name.localeCompare(b.name));

  const doc = {
    schemaVersion: 1,
    datasetVersion: VERSION,
    attribution: 'District/upazila/thana names derived from @olism/bd-geo ' +
      '(MIT, https://github.com/mohammad-oliullah/bd-geo). English spelling variants curated in-repo.',
    generatedAt: new Date().toISOString().slice(0, 10),
    districts: out
  };

  const dataDir = path.join(root, 'data');
  fs.mkdirSync(dataDir, { recursive: true });
  fs.writeFileSync(path.join(dataDir, 'bd-locations.json'), JSON.stringify(doc, null, 2) + '\n');

  const bundle = '/* GENERATED by tools/gen-bd-locations.js from ' + VERSION + ' - do not edit by hand.\n' +
    '   ' + doc.attribution + ' */\n' +
    'window.BD_LOCATIONS = ' + JSON.stringify(doc) + ';\n';
  fs.writeFileSync(path.join(root, 'js', 'bd-locations.js'), bundle);

  const nThana = out.reduce((a, d) => a + d.thanas.length, 0);
  console.log('wrote data/bd-locations.json and js/bd-locations.js: ' +
    out.length + ' districts, ' + nThana + ' thanas');
})().catch(e => { console.error('generation failed: ' + e.message); process.exit(1); });
